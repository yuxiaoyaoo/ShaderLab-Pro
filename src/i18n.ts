export function nodeCategoryLabel(category: string): string {
  const key = categoryKeys[category];
  return key ? t(key) : category;
}

export type TemplateDifficulty = 'beginner' | 'intermediate' | 'advanced';

export function normalizeDifficulty(value: string): TemplateDifficulty {
  const normalized = value.trim().toLocaleLowerCase();
  if (normalized === 'intermediate' || normalized === '进阶') return 'intermediate';
  if (normalized === 'advanced' || normalized === '高级') return 'advanced';
  if (normalized === 'beginner' || normalized === '入门') return 'beginner';
  return 'beginner';
}

export function difficultyLabel(value: string): string {
  return t(`template.difficulty.${normalizeDifficulty(value)}`);
}

export function joinLocalized(items: readonly string[], style: 'semicolon' | 'comma' = 'semicolon'): string {
  const separator = style === 'comma'
    ? (locale() === 'en' ? ', ' : '、')
    : (locale() === 'en' ? '; ' : '；');
  return items.filter(Boolean).join(separator);
}

export function localizedDetail(detail: string): string {
  return detail ? `${locale() === 'en' ? ': ' : '：'}${detail}` : '';
}
