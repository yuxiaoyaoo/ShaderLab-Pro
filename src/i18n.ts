type AdditionalTranslationKey = keyof typeof additionalMessages;
export type TranslationKey = BaseTranslationKey | AdditionalTranslationKey;

function messagesFor(localeValue: Locale): Record<AdditionalTranslationKey, string> {
  return Object.fromEntries(
    Object.entries(additionalMessages).map(([key, messages]) => [key, messages[localeValue]]),
  ) as Record<AdditionalTranslationKey, string>;
}

const zhCN: Record<TranslationKey, string> = { ...baseZhCN, ...messagesFor('zh-CN') };
const en: Record<TranslationKey, string> = { ...baseEn, ...messagesFor('en') };

export const translationCatalogs: Readonly<Record<Locale, Readonly<Record<TranslationKey, string>>>> = {
  'zh-CN': zhCN,
  en,
};

function readInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh-CN' || saved === 'en') return saved;
  } catch {
    // Storage can be unavailable in restricted browser contexts.
  }
  return 'zh-CN';
}

const [locale, setLocaleSignal] = createSignal<Locale>(readInitialLocale());

function syncDocumentLanguage(value: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = value;
}

syncDocumentLanguage(locale());

export { locale };

export function setLocale(value: Locale) {
  setLocaleSignal(value);
  syncDocumentLanguage(value);
  try {
    localStorage.setItem(STORAGE_KEY, value);
  } catch {
    // Keep the in-memory preference when persistence is unavailable.
  }
}

export function toggleLocale() {
  setLocale(locale() === 'zh-CN' ? 'en' : 'zh-CN');
}

export function t(key: TranslationKey, params?: TranslationParams): string {
  const template = translationCatalogs[locale()][key];
  if (!params) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

